const { chromium } = require('playwright');
const path = require('node:path');
const assert = require('node:assert/strict');
const fs = require('node:fs');
async function main(){
  const out=path.join(__dirname,'previews');fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true,...(process.env.PREVIEW_BROWSER?{executablePath:process.env.PREVIEW_BROWSER}:{channel:'chrome'})});
  const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.PREVIEW_URL || require('node:url').pathToFileURL(path.join(__dirname,'../index.html')).href);await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.locator('.screen-grid .phone').count(),6);
  console.log('Gallery geometry',await page.locator('.screen-grid .phone-content').evaluateAll(els=>els.map(el=>({screen:el.closest('.phone').dataset.phoneScreen,width:el.clientWidth,scrollWidth:el.scrollWidth,height:el.clientHeight,contentHeight:el.scrollHeight}))));
  await page.screenshot({path:path.join(out,'six-screens.png'),fullPage:true});
  const grid=await page.locator('.screen-grid').boundingBox();
  const row2=await page.locator('.mockup-wrap').nth(3).boundingBox();
  await page.screenshot({path:path.join(out,'screens-01-03.png'),fullPage:true,clip:{x:grid.x-6,y:grid.y-4,width:grid.width+12,height:row2.y-grid.y-26}});
  await page.screenshot({path:path.join(out,'screens-04-06.png'),fullPage:true,clip:{x:grid.x-6,y:row2.y-4,width:grid.width+12,height:grid.y+grid.height-row2.y+12}});
  await page.getByRole('button',{name:'Användarflöde',exact:true}).click();
  await page.screenshot({path:path.join(out,'user-flow.png'),fullPage:true});
  await page.getByRole('button',{name:'Prova appen',exact:false}).click();
  const live=page.locator('#live-phone');
  await live.getByRole('button',{name:'Kunder',exact:true}).click();
  await live.getByRole('button',{name:'Lägg till kund',exact:true}).last().click();
  await live.getByLabel('Namn',{exact:true}).fill('Sara Andersson');
  await live.getByLabel('E-post',{exact:true}).fill('sara@example.com');
  await live.getByLabel('Arbetsadress',{exact:true}).fill('Parkvägen 5');
  await live.getByLabel('Postnummer och ort',{exact:true}).fill('431 42 Mölndal');
  await live.getByRole('button',{name:'Spara kund'}).click();
  await live.getByRole('button',{name:'Skapa jobb för kunden'}).click();
  await live.getByLabel('Vad ska göras?').fill('Byta vägguttag');
  await live.getByRole('button',{name:'Boka jobbet'}).click();
  assert.match(await live.innerText(),/Sara Andersson/);
  await live.getByRole('button',{name:'Tid & material',exact:true}).click();
  await live.getByRole('button',{name:'Lägg till tid',exact:true}).click();
  await live.getByRole('button',{name:'Spara tid'}).click();
  await live.getByRole('button',{name:'Lägg till material',exact:true}).click();
  await live.getByLabel('Benämning').fill('Jordat uttag');
  await live.getByLabel('Antal',{exact:true}).fill('2');
  await live.getByLabel('Försäljningspris / enhet, exkl. moms').fill('100');
  await live.getByRole('button',{name:'Spara material'}).click();
  await live.getByRole('button',{name:'Klart',exact:true}).click();
  await live.getByRole('button',{name:'Skapa fakturautkast'}).click();
  assert.match(await live.locator('.invoice-total').innerText(),/1 625,00/);
  await live.getByRole('button',{name:'ROT-avdrag',exact:false}).click();
  await live.getByLabel('Fastighetsbeteckning').fill('Demo Eken 1:23');
  await live.getByRole('checkbox').check();
  await live.getByRole('button',{name:'Visa preliminärt avdrag'}).click();
  assert.match(await live.locator('.invoice-total').innerText(),/1 343,75/);
  await live.getByRole('button',{name:'Granska & skicka'}).click();
  await live.getByRole('checkbox').check();
  await live.getByRole('button',{name:'Simulera utskick'}).click();
  await live.getByRole('button',{name:'Markera som betald'}).click();
  assert.match(await live.innerText(),/Markerad som betald/);
  await live.getByRole('button',{name:'Fakturor',exact:true}).click();
  await live.getByRole('button',{name:'Förfallna',exact:true}).click();
  assert.equal(await live.locator('.invoice-list-row').count(),1);
  assert.match(await live.locator('.invoice-list-row').innerText(),/Martin Lind/);
  await live.getByRole('button',{name:'Utkast',exact:true}).click();
  assert.match(await live.innerText(),/Inga fakturautkast kvar/);
  console.log('Customer → job → time/material → invoice → ROT → simulated send → paid: OK');
  await page.getByRole('button',{name:'Börja om med exempeldata'}).click();
  await live.getByRole('button',{name:'Öppna jobbet'}).click();
  await live.getByRole('button',{name:'Starta timer'}).click();
  assert.equal(await live.locator('[data-timer]').count(),1);
  await live.getByRole('button',{name:'Stoppa och spara tid',exact:true}).click();
  assert.equal(await live.locator('[data-timer]').count(),0);
  console.log('Timer start/stop: OK');
  await page.getByRole('button',{name:'Börja om med exempeldata'}).click();
  await page.setViewportSize({width:390,height:844});
  await live.locator('.toast').evaluateAll(els=>els.forEach(el=>el.remove()));
  await live.locator('.phone').screenshot({path:path.join(out,'mobile-home.png')});
  await live.getByRole('button',{name:'Kunder',exact:true}).click();
  await live.getByRole('textbox',{name:'Sök kund eller adress'}).fill('no-such-customer');
  assert.match(await live.innerText(),/Ingen kund matchar/);
  await page.setViewportSize({width:320,height:844});
  const sizes=await page.evaluate(()=>({viewport:innerWidth,body:document.body.scrollWidth,phone:document.querySelector('#live-phone .phone-content').scrollWidth,inner:document.querySelector('#live-phone .phone-content').clientWidth}));
  assert(sizes.body<=sizes.viewport,JSON.stringify(sizes));assert(sizes.phone<=sizes.inner,JSON.stringify(sizes));
  await live.locator('.phone').screenshot({path:path.join(out,'mobile-narrow.png')});
  assert.deepEqual(errors,[]);console.log('390px and 320px mobile, search empty state, no browser errors: OK');
  await browser.close();
}
main().catch(e=>{console.error(e);process.exit(1);});
